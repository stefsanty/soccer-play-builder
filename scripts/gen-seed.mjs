// Generates supabase/seed/<slug>.{json,sql} for each seed play in src/lib/seed/.
// The SQL updates the play in place when one with the same title exists (so its id and links stay stable) and
// inserts it otherwise. Placeholder titles listed in `replaces` are deleted.
// Run: node scripts/gen-seed.mjs   (Node 22.6+/24 strips the TypeScript types itself)
import { writeFileSync } from 'node:fs'
import { toPlayInsert as rightSideBuildUp } from '../src/lib/seed/rightSideBuildUp.ts'
import { toPlayInsert as defensiveAiTest } from '../src/lib/seed/defensiveAiTest.ts'

const seeds = [
  { slug: 'right-side-build-up', play: rightSideBuildUp(), replaces: ['Sample Play'] },
  { slug: 'defensive-ai-test', play: defensiveAiTest(), replaces: [] },
]

const lit = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`
const q = (s) => `'${s.replaceAll("'", "''")}'`

for (const { slug, play, replaces } of seeds) {
  // Infinity is already null in the converted data
  writeFileSync(new URL(`../supabase/seed/${slug}.json`, import.meta.url), JSON.stringify(play, null, 2) + '\n')
  const title = q(play.title)
  const cols = {
    description: q(play.description),
    author_name: q(play.authorName),
    formation: q(play.meta.formation),
    is_public: 'true',
    tags: q(`{${play.meta.tags.join(',')}}`),
    view_side: q(play.meta.viewSide),
    players: lit(play.players),
    steps: lit(play.steps),
  }
  const names = Object.keys(cols)
  const sql = `-- ${play.title} (generated by scripts/gen-seed.mjs; do not edit by hand)
-- Updates the play in place if it exists (same id), otherwise inserts it${replaces.length ? `; removes the placeholder ${replaces.map(q).join(', ')}` : ''}.
begin;
${replaces.length ? `delete from plays where title in (${replaces.map(q).join(', ')});\n` : ''}with upd as (
  update plays set ${names.map((n) => `${n} = ${cols[n]}`).join(',\n    ')}
  where title = ${title}
  returning id
)
insert into plays (title, ${names.join(', ')})
select ${title}, ${names.map((n) => cols[n]).join(', ')}
where not exists (select 1 from upd);
select id, title, jsonb_array_length(players) as players, jsonb_array_length(steps) as steps from plays where title = ${title};
commit;
`
  writeFileSync(new URL(`../supabase/seed/${slug}.sql`, import.meta.url), sql)
  console.log(`${slug}: players=${play.players.length} steps=${play.steps.length}`)
}
