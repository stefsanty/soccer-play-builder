// Generates supabase/seed/<slug>.{json,sql} for each seed play in src/lib/seed/.
// Run: node scripts/gen-seed.mjs   (Node 22.6+/24 strips the TypeScript types itself)
import { writeFileSync } from 'node:fs'
import { toPlayInsert as rightSideBuildUp } from '../src/lib/seed/rightSideBuildUp.ts'
import { toPlayInsert as defensiveAiTest } from '../src/lib/seed/defensiveAiTest.ts'

const seeds = [
  { slug: 'right-side-build-up', play: rightSideBuildUp(), replaces: ['Sample Play'] },
  { slug: 'defensive-ai-test', play: defensiveAiTest(), replaces: [] },
]

const lit = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`
const q = (s) => `'${s.replaceAll("'", "''")}'`

for (const { slug, play, replaces } of seeds) {
  // Infinity is already null in the converted data
  writeFileSync(new URL(`../supabase/seed/${slug}.json`, import.meta.url), JSON.stringify(play, null, 2) + '\n')
  const titles = [...replaces, play.title].map(q).join(', ')
  const sql = `-- ${play.title} (generated by scripts/gen-seed.mjs; do not edit by hand)
-- Replaces any earlier copy of this play${replaces.length ? ` and the placeholder ${replaces.map(q).join(', ')}` : ''}.
begin;
delete from plays where title in (${titles});
insert into plays (title, description, author_name, formation, is_public, tags, view_side, players, steps)
values (
  ${q(play.title)},
  ${q(play.description)},
  ${q(play.authorName)},
  ${q(play.meta.formation)},
  true,
  ${q(`{${play.meta.tags.join(',')}}`)},
  ${q(play.meta.viewSide)},
  ${lit(play.players)},
  ${lit(play.steps)}
)
returning id, title, jsonb_array_length(players) as players, jsonb_array_length(steps) as steps;
commit;
`
  writeFileSync(new URL(`../supabase/seed/${slug}.sql`, import.meta.url), sql)
  console.log(`${slug}: players=${play.players.length} steps=${play.steps.length}`)
}
