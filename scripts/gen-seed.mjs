// Generates supabase/seed/right-side-build-up.{json,sql} from src/lib/seed/rightSideBuildUp.ts.
// Run: node scripts/gen-seed.mjs   (Node 22.6+/24 strips the TypeScript types itself)
import { writeFileSync } from 'node:fs'
import { toPlayInsert } from '../src/lib/seed/rightSideBuildUp.ts'

const play = toPlayInsert()
const json = JSON.stringify(play, null, 2) // Infinity is already null in the converted data

writeFileSync(new URL('../supabase/seed/right-side-build-up.json', import.meta.url), json + '\n')

const lit = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`
const q = (s) => `'${s.replaceAll("'", "''")}'`
const sql = `-- Right-side build-up: 4-5-1 (generated by scripts/gen-seed.mjs; do not edit by hand)
-- Replaces the placeholder "Sample Play" and any earlier copy of this play.
begin;
delete from plays where title in ('Sample Play', ${q(play.title)});
insert into plays (title, description, author_name, formation, is_public, tags, view_side, players, steps)
values (
  ${q(play.title)},
  ${q(play.description)},
  ${q(play.authorName)},
  ${q(play.meta.formation)},
  true,
  '{}',
  ${q(play.meta.viewSide)},
  ${lit(play.players)},
  ${lit(play.steps)}
)
returning id, title, jsonb_array_length(players) as players, jsonb_array_length(steps) as steps;
commit;
`
writeFileSync(new URL('../supabase/seed/right-side-build-up.sql', import.meta.url), sql)
console.log(`players=${play.players.length} steps=${play.steps.length}`)
